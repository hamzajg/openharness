def list_bundles(repo: Path | str, feature: str | None = None) -> list[dict[str, Any]]:
    """Every bundle under the local root, newest first, with its headline facts."""
    root = bundle_root(repo)
    if not root.is_dir():
        return []
    pattern = f"{feature}/*/evidence.json" if feature else "*/*/evidence.json"
    out: list[dict[str, Any]] = []
    for manifest_path in sorted(root.glob(pattern), reverse=True):
        bundle = manifest_path.parent
        try:
            m = load(bundle)
        except EvidenceError as ex:
            out.append(
                {
                    "bundle": bundle,
                    "feature": bundle.parent.name,
                    "run_id": bundle.name,
                    "invalid": str(ex),
                }
            )
            continue
        out.append(
            {
                "bundle": bundle,
                "feature": m["feature"],
                "wave": m.get("wave"),
                "run_id": m["run_id"],
                "verdict": m["verdict"],
                "head": (m.get("repo") or {}).get("head") or "",
                "steps": len(m.get("steps") or []),
                "artifacts": sum(len(s.get("artifacts") or []) for s in m.get("steps") or []),
                "summary": m.get("summary") or "",
            }
        )
    return out
