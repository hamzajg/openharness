"""Evidence bundles: the manifest, its checks, and the walkthrough page.

A bundle is proof of one run, stored in the repo's local scratch directory:

    .openharness/evidence/<feature>/<run-id>/
    ├── evidence.json   manifest (authoritative)
    ├── index.html      generated by `render`
    ├── SUMMARY.md      generated by `render`
    ├── raw/            screenshots, recordings, traces
    └── logs/           one file per executed command

Nothing here touches the network and nothing writes to git. `verify` reads git
only to answer two questions: does this bundle sit in a tracked directory, and
does the manifest's commit match HEAD.

The point of the checks is that a bundle cannot back a claim it does not
support: every artifact is re-hashed, a missing file is an error, a token in a
log is an error, and evidence recorded against a different commit is an error.
"""

from __future__ import annotations

import base64
import hashlib
import html
import json
import re
import subprocess as sp
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

SCHEMA = "openharness.evidence/1"
ROOT = Path(".openharness") / "evidence"

KINDS = ("command", "browser", "api", "manual")
STATUSES = ("pass", "fail", "skip", "manual")
VERDICTS = ("pass", "fail", "partial")

#: Inline mode refuses to grow the page past this; images beyond it stay linked.
INLINE_BUDGET = 6 * 1024 * 1024

_TEXT_SUFFIXES = {
    ".log", ".txt", ".json", ".md", ".csv", ".yaml", ".yml", ".toml", ".xml",
}


class EvidenceError(Exception):
    """A bundle could not be created, read, or rendered."""


@dataclass
class Finding:
    """One check result. `error` is fatal; `warning` is worth reading."""

    severity: str
    code: str
    message: str

    def render(self) -> str:
        return f"- [{self.code}] {self.message}"


@dataclass
class Report:
    bundle: Path
    findings: list[Finding] = field(default_factory=list)

    @property
    def errors(self) -> list[Finding]:
        return [f for f in self.findings if f.severity == "error"]

    @property
    def warnings(self) -> list[Finding]:
        return [f for f in self.findings if f.severity == "warning"]

    @property
    def ok(self) -> bool:
        return not self.errors

    def render(self) -> str:
        head = f"# Evidence — {self.bundle}"
        if self.ok:
            head += "\n\nOK — the bundle matches its own manifest."
        else:
            head += f"\n\nFAILED ({len(self.errors)} error(s), {len(self.warnings)} warning(s))."
        lines = [head]
        if self.errors:
            lines += ["", "Errors:", *[f.render() for f in self.errors]]
        if self.warnings:
            lines += ["", "Warnings:", *[f.render() for f in self.warnings]]
        return "\n".join(lines)


# --------------------------------------------------------------------- paths

def bundle_root(repo: Path | str) -> Path:
    """Where bundles live by default: local scratch, gitignored, never tracked."""
    return Path(repo) / ROOT


def run_id(head: str, now: datetime | None = None) -> str:
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y%m%dT%H%M%SZ")
    return f"{stamp}-{(head or 'unknown')[:7]}"


def new_bundle(
    repo: Path | str,
    feature: str,
    *,
    wave: int = 0,
    head: str = "",
    branch: str = "",
    base: str = "main",
    summary: str = "",
    not_verified: Iterable[str] = (),
    run: str | None = None,
) -> Path:
    """Create an empty bundle and its manifest; returns the bundle directory."""
    if not feature.strip():
        raise EvidenceError("feature is required")
    # Record the commit this evidence belongs to; `verify` refuses an empty one
    # rather than letting a bundle float free of the run it describes.
    head = head or (_git_head(Path(repo)) or "")
    root = bundle_root(repo)
    bundle = root / feature.strip() / (run or run_id(head))
    if bundle.exists():
        raise EvidenceError(f"bundle already exists: {bundle}")
    for sub in ("raw", "logs"):
        (bundle / sub).mkdir(parents=True, exist_ok=True)
    manifest = {
        "schema": SCHEMA,
        "feature": feature.strip(),
        "wave": int(wave),
        "run_id": bundle.name,
        "created_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "repo": {"slug": "", "branch": branch, "head": head, "base": base},
        "ci": {"pr": None, "url": None, "sha": None, "conclusion": None},
        "verdict": "pass",
        "summary": summary,
        "not_verified": [str(x) for x in not_verified],
        "steps": [],
        "redactions": [],
        "environment": {},
    }
    _write_manifest(bundle, manifest)
    return bundle


def _write_manifest(bundle: Path, manifest: dict) -> Path:
    path = bundle / "evidence.json"
    path.write_text(json.dumps(manifest, indent=2) + "\n")
    return path


def load(bundle: Path | str) -> dict[str, Any]:
    """Read and validate a manifest; raises EvidenceError listing every fault."""
    path = Path(bundle) / "evidence.json"
    if not path.is_file():
        raise EvidenceError(f"no evidence.json in {bundle}")
    try:
        manifest = json.loads(path.read_text())
    except ValueError as ex:
        raise EvidenceError(f"evidence.json is not valid JSON: {ex}") from ex
    problems = _schema_problems(manifest)
    if problems:
        raise EvidenceError("invalid manifest:\n  - " + "\n  - ".join(problems))
    return manifest


def _schema_problems(m: Any) -> list[str]:
    if not isinstance(m, dict):
        return ["manifest must be an object"]
    out: list[str] = []
    if m.get("schema") != SCHEMA:
        out.append(f"schema must be {SCHEMA!r}, got {m.get('schema')!r}")
    for key in ("feature", "run_id", "created_at"):
        if not isinstance(m.get(key), str) or not m.get(key).strip():
            out.append(f"{key} must be a non-empty string")
    if m.get("verdict") not in VERDICTS:
        out.append(f"verdict must be one of {VERDICTS}, got {m.get('verdict')!r}")
    if not isinstance(m.get("not_verified"), list):
        out.append("not_verified must be a list (possibly empty)")
    if not isinstance(m.get("repo"), dict):
        out.append("repo must be an object")
    if not isinstance(m.get("steps"), list):
        out.append("steps must be a list")
        return out
    seen: set[str] = set()
    for i, step in enumerate(m["steps"]):
        where = f"steps[{i}]"
        if not isinstance(step, dict):
            out.append(f"{where} must be an object")
            continue
        sid = step.get("id")
        if not isinstance(sid, str) or not sid:
            out.append(f"{where}.id must be a non-empty string")
        elif sid in seen:
            out.append(f"{where}.id {sid!r} is duplicated")
        else:
            seen.add(sid)
        if not isinstance(step.get("title"), str):
            out.append(f"{where}.title must be a string")
        if step.get("kind") not in KINDS:
            out.append(f"{where}.kind must be one of {KINDS}")
        if step.get("status") not in STATUSES:
            out.append(f"{where}.status must be one of {STATUSES}")
        if step.get("kind") == "command" and not isinstance(step.get("exit_code"), int):
            out.append(f"{where}.exit_code must be an integer for a command step")
        if step.get("log") is not None and not isinstance(step.get("log"), str):
            out.append(f"{where}.log must be a path string")
        arts = step.get("artifacts", [])
        if not isinstance(arts, list):
            out.append(f"{where}.artifacts must be a list")
            continue
        for j, art in enumerate(arts):
            aw = f"{where}.artifacts[{j}]"
            if not isinstance(art, dict):
                out.append(f"{aw} must be an object")
                continue
            for key in ("path", "mime", "sha256"):
                if not isinstance(art.get(key), str) or not art.get(key):
                    out.append(f"{aw}.{key} must be a non-empty string")
            if not isinstance(art.get("bytes"), int):
                out.append(f"{aw}.bytes must be an integer")
    return out


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def iter_artifacts(manifest: dict) -> Iterable[tuple[dict, dict]]:
    for step in manifest.get("steps", []):
        for art in step.get("artifacts", []) or []:
            yield step, art


# -------------------------------------------------------------------- checks

_SECRET_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("github-token", re.compile(r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{20,}")),
    ("github-pat", re.compile(r"\bgithub_pat_[A-Za-z0-9_]{20,}")),
    ("openai-key", re.compile(r"\bsk-[A-Za-z0-9]{20,}")),
    ("aws-access-key", re.compile(r"\bAKIA[0-9A-Z]{16}\b")),
    ("slack-token", re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{10,}")),
    (
        "bearer-token",
        re.compile(r"(?i)\bauthorization\s*:\s*bearer\s+(?!\[REDACTED\])[A-Za-z0-9._~+/=-]{16,}"),
    ),
    ("private-key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----")),
)

_ALLOWED_REDACTED = ("[REDACTED]", "<redacted>", "REDACTED")


def _is_text(path: Path, mime: str = "") -> bool:
    return mime.startswith("text/") or path.suffix.lower() in _TEXT_SUFFIXES


def _secret_hits(path: Path) -> list[tuple[str, int]]:
    """(pattern name, line number) for token-shaped strings in a text file."""
    try:
        text = path.read_text(errors="replace")
    except OSError:
        return []
    hits: list[tuple[str, int]] = []
    for name, pattern in _SECRET_PATTERNS:
        for match in pattern.finditer(text):
            line = text.count("\n", 0, match.start()) + 1
            hits.append((name, line))
            break  # one hit per pattern is enough to fail the bundle
    return hits


def _git(repo: Path, *args: str) -> sp.CompletedProcess:
    return sp.run(
        ["git", "-C", str(repo), *args],
        capture_output=True,
        text=True,
    )


def _git_head(repo: Path) -> str | None:
    run = _git(repo, "rev-parse", "HEAD")
    return run.stdout.strip() if run.returncode == 0 else None


def _tracked_files(repo: Path, bundle: Path) -> list[str]:
    """Paths under `bundle` that git is tracking; empty when it cannot tell."""
    try:
        rel = bundle.resolve().relative_to(repo.resolve())
    except ValueError:
        return []
    run = _git(repo, "ls-files", "--", rel.as_posix())
    if run.returncode != 0:
        return []
    return [line for line in run.stdout.splitlines() if line.strip()]


def verify(
    bundle: Path | str,
    repo: Path | str | None = None,
    head: str | None = None,
) -> Report:
    """Check a bundle against its manifest, the files on disk, and git.

    `repo` defaults to the bundle's repository root when it can be found, else
    the current directory. `head` overrides the commit the manifest is compared
    against (defaults to `git rev-parse HEAD`).
    """
    bundle = Path(bundle)
    report = Report(bundle=bundle)
    if not bundle.is_dir():
        report.findings.append(Finding("error", "missing-bundle", f"{bundle} is not a directory"))
        return report
    try:
        manifest = load(bundle)
    except EvidenceError as ex:
        report.findings.append(Finding("error", "invalid-manifest", str(ex)))
        return report

    repo_path = Path(repo) if repo is not None else _guess_repo(bundle)

    # -- the bundle itself must be local and untracked
    tracked = _tracked_files(repo_path, bundle) if repo_path else []
    if tracked:
        report.findings.append(
            Finding(
                "error",
                "tracked-bundle",
                "bundle is tracked by git (evidence must stay local): "
                + ", ".join(tracked[:3])
                + (" …" if len(tracked) > 3 else ""),
            )
        )
    elif repo_path is None or _git_head(repo_path) is None:
        report.findings.append(
            Finding("warning", "no-git", "no git repository found; cannot confirm the bundle is untracked")
        )

    # -- commit binding
    recorded = (manifest.get("repo") or {}).get("head") or ""
    expected = head or (_git_head(repo_path) if repo_path else None)
    if not recorded:
        report.findings.append(Finding("error", "no-commit", "manifest.repo.head is empty"))
    elif expected is None:
        report.findings.append(
            Finding("warning", "no-head", "git HEAD unavailable; commit binding not checked")
        )
    elif not _same_commit(recorded, expected):
        report.findings.append(
            Finding(
                "error",
                "commit-mismatch",
                f"manifest claims {recorded} but the checked commit is {expected}",
            )
        )

    # -- verdict vs steps
    a_recorded = manifest["verdict"]
    bad_steps = [
        s for s in manifest["steps"]
        if s.get("status") == "fail" and not s.get("expected_failure")
    ]
    if a_recorded == "pass" and bad_steps:
        names = ", ".join(s.get("id", "?") for s in bad_steps)
        report.findings.append(
            Finding(
                "error",
                "verdict-contradicts-steps",
                f"verdict is pass but steps failed: {names} (mark expected_failure to allow)",
            )
        )
    for step in manifest["steps"]:
        if step.get("kind") != "command":
            continue
        code = step.get("exit_code")
        if step.get("status") == "pass" and code != 0:
            report.findings.append(
                Finding(
                    "error",
                    "exit-code-contradicts-status",
                    f"step {step.get('id')} is pass but exit_code is {code}",
                )
            )
        if step.get("status") == "fail" and code == 0 and not step.get("expected_failure"):
            report.findings.append(
                Finding(
                    "warning",
                    "zero-exit-failure",
                    f"step {step.get('id')} is fail but exit_code is 0",
                )
            )

    # -- logs and artifacts must exist, and match their hashes
    for step in manifest["steps"]:
        log = step.get("log")
        if log:
            path = bundle / log
            if not path.is_file():
                report.findings.append(
                    Finding("error", "missing-log", f"step {step.get('id')}: {log} does not exist")
                )
            else:
                for name, line in _secret_hits(path):
                    report.findings.append(
                        Finding(
                            "error",
                            "secret-in-log",
                            f"{log}:{line} looks like a {name} (redact it before rendering)",
                        )
                    )
    for step, art in iter_artifacts(manifest):
        rel = art["path"]
        path = bundle / rel
        if not path.is_file():
            report.findings.append(
                Finding("error", "missing-artifact", f"step {step.get('id')}: {rel} does not exist")
            )
            continue
        size = path.stat().st_size
        if art.get("bytes") != size:
            report.findings.append(
                Finding(
                    "error",
                    "size-mismatch",
                    f"{rel} is {size} bytes, manifest says {art.get('bytes')}",
                )
            )
        digest = sha256(path)
        if digest != art.get("sha256"):
            report.findings.append(
                Finding(
                    "error",
                    "hash-mismatch",
                    f"{rel} hashes to {digest[:12]}…, manifest says {art['sha256'][:12]}…",
                )
            )
        if _is_text(path, art.get("mime", "")):
            for name, line in _secret_hits(path):
                report.findings.append(
                    Finding(
                        "error",
                        "secret-in-artifact",
                        f"{rel}:{line} looks like a {name} (redact it before rendering)",
                    )
                )

    # -- an empty bundle is structurally fine and evidentially worthless
    if not manifest["steps"]:
        report.findings.append(
            Finding(
                "warning",
                "empty-bundle",
                "no steps were recorded — this bundle proves nothing yet",
            )
        )

    # -- the page must not advertise a CI run it cannot name
    ci = manifest.get("ci") or {}
    if ci.get("conclusion") == "success" and not ci.get("sha"):
        report.findings.append(
            Finding("error", "ci-without-sha", "ci.conclusion is success but ci.sha is missing")
        )
    if ci.get("sha") and ci.get("sha") != recorded:
        report.findings.append(
            Finding(
                "warning",
                "ci-sha-differs",
                f"ci.sha {ci['sha']} differs from repo.head {recorded}",
            )
        )

    return report


def _same_commit(a: str, b: str) -> bool:
    a, b = (a or "").strip(), (b or "").strip()
    if not a or not b:
        return False
    if a == b:
        return True
    short, full = (a, b) if len(a) <= len(b) else (b, a)
    return len(short) >= 7 and full.startswith(short)


def _guess_repo(bundle: Path) -> Path | None:
    """Walk up looking for a repo containing `.openharness/` or `.git`."""
    for parent in [bundle, *bundle.parents]:
        if (parent / ".git").exists() or (parent / ".openharness").is_dir():
            return parent
    return None


# -------------------------------------------------------------------- render

def render(bundle: Path | str, inline: bool = False) -> dict[str, Path]:
    """Write `index.html` and `SUMMARY.md` from the manifest; returns their paths."""
    bundle = Path(bundle)
    manifest = load(bundle)
    html_path = bundle / "index.html"
    md_path = bundle / "SUMMARY.md"
    html_path.write_text(_page(manifest, bundle, inline=inline))
    md_path.write_text(summary_markdown(manifest))
    return {"html": html_path, "summary": md_path}


def summary_markdown(manifest: dict) -> str:
    repo = manifest.get("repo") or {}
    ci = manifest.get("ci") or {}
    steps = manifest.get("steps") or []
    arts = [a for _, a in iter_artifacts(manifest)]
    images = [a for a in arts if a.get("mime", "").startswith("image/")]
    videos = [a for a in arts if a.get("mime", "").startswith("video/")]
    lines = [
        f"## Evidence — {manifest['feature']}"
        + (f" · wave {manifest['wave']}" if manifest.get("wave") else ""),
        "",
        f"- verdict: **{manifest['verdict']}**",
        f"- run: `{manifest['run_id']}`",
        f"- head: `{repo.get('head') or 'unknown'}`"
        + (f" on `{repo['branch']}`" if repo.get("branch") else ""),
    ]
    if ci.get("pr"):
        lines.append(f"- CI: PR #{ci['pr']} — {ci.get('conclusion') or 'unknown'} @ `{ci.get('sha') or '?'}`")
    if manifest.get("summary"):
        lines += ["", manifest["summary"]]
    lines += [
        "",
        f"- steps: {len(steps)} · artifacts: {len(arts)}"
        f" · screenshots: {len(images)} · recordings: {len(videos)}",
    ]
    not_verified = manifest.get("not_verified") or []
    if not_verified:
        lines += ["", "**Not verified:** " + "; ".join(not_verified)]
    if not steps and not arts:
        lines += ["", "_Nothing was captured in this run — this bundle proves nothing yet._"]
    return "\n".join(lines) + "\n"


def _page(manifest: dict, bundle: Path, inline: bool) -> str:
    repo = manifest.get("repo") or {}
    ci = manifest.get("ci") or {}
    steps = manifest.get("steps") or []
    arts = [a for _, a in iter_artifacts(manifest)]
    images = [a for a in arts if a.get("mime", "").startswith("image/")]
    videos = [a for a in arts if a.get("mime", "").startswith("video/")]
    verdict = manifest["verdict"]
    e = html.escape
    empty = not steps and not arts

    chips = [
        f'<span class="chip verdict v-{e(verdict)}"><b>{e(verdict.upper())}</b></span>',
        f'<span class="chip">run <b>{e(manifest["run_id"])}</b></span>',
    ]
    if repo.get("head"):
        chips.append(f'<span class="chip">head <b>{e(repo["head"])}</b></span>')
    if repo.get("branch"):
        chips.append(f'<span class="chip">branch <b>{e(repo["branch"])}</b></span>')
    if ci.get("pr"):
        chips.append(f'<span class="chip">PR <b>#{e(str(ci["pr"]))}</b></span>')
    if ci.get("conclusion"):
        chips.append(
            f'<span class="chip">CI <b>{e(str(ci["conclusion"]))}</b>'
            + (f' @ {e(str(ci.get("sha")))}' if ci.get("sha") else "")
            + "</span>"
        )

    parts = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>Evidence — {e(manifest['feature'])} · {e(manifest['run_id'])}</title>",
        f"<style>{_CSS}</style></head><body><main>",
        f'<p class="sub">Evidence bundle · generated from evidence.json · {e(SCHEMA)}</p>',
        f"<h1>{e(manifest['feature'])}"
        + (f" — wave {e(str(manifest['wave']))}" if manifest.get("wave") else "")
        + "</h1>",
        '<div class="chips">' + "".join(chips) + "</div>",
        "<h2>What this proves</h2>",
    ]
    if manifest.get("summary"):
        parts.append(f'<div class="card">{e(manifest["summary"])}</div>')
    else:
        parts.append('<div class="card"><em>No summary was recorded for this run.</em></div>')

    counts = (
        f"steps {len(steps)} · artifacts {len(arts)} · screenshots {len(images)}"
        f" · recordings {len(videos)}"
    )
    parts.append(f'<p class="sub">{e(counts)}</p>')

    not_verified = manifest.get("not_verified") or []
    if not_verified:
        items = "".join(f"<li>{e(str(x))}</li>" for x in not_verified)
        parts.append(
            '<div class="card notverified"><strong>What was not verified</strong>'
            f"<ul>{items}</ul></div>"
        )

    if empty:
        parts.append(
            '<div class="card empty"><strong>Nothing was captured in this run.</strong>'
            "<p>No steps, screenshots, recordings or logs are attached to this bundle, "
            "so it proves nothing yet. Record at least one step before using it as "
            "evidence for a wave.</p></div>"
        )

    # -- walkthrough
    if steps:
        parts.append("<h2>Walkthrough</h2>")
        for step in steps:
            status = step.get("status", "manual")
            dur = step.get("duration_ms")
            note = step.get("note")
            expected = step.get("expected_failure")
            details = [
                f'<div class="step {e(status)}">',
                f'<span class="dot"></span><div>',
                f'<div><b>{e(step.get("title") or step.get("id") or "")}</b> '
                f'<span class="pill">{e(status)}</span>'
                + (' <span class="note">(expected failure)</span>' if expected else "")
                + "</div>",
            ]
            if step.get("cmd"):
                details.append(f'<div class="cmd">{e(step["cmd"])}</div>')
            if note:
                details.append(f'<div class="note">{e(str(note))}</div>')
            details.append("</div>")
            details.append(f'<span class="note">{e(_duration(dur))}</span></div>')
            parts.append("".join(details))

    # -- screenshots
    if images:
        parts.append("<h2>Screenshots</h2><div class=\"gallery\">")
        for art in images:
            src = _src(art, bundle, inline)
            caption = art.get("caption") or art["path"]
            parts.append(
                "<figure>"
                f'<a href="{e(_rel_src(art))}"><img src="{e(src)}" alt="{e(str(caption))}" loading="lazy"></a>'
                f"<figcaption><b>{e(str(caption))}</b><br>"
                f'<span class="mono">sha256 {e(art["sha256"][:12])}…</span></figcaption>'
                "</figure>"
            )
        parts.append("</div>")

    # -- recording
    if videos:
        parts.append("<h2>Recording</h2>")
        for art in videos:
            src = _rel_src(art)
            parts.append(
                '<div class="card">'
                f'<video controls preload="metadata" src="{e(src)}"></video>'
                f'<p class="note">{e(art.get("caption") or art["path"])} · '
                f'{e(_size(art.get("bytes")))} · sha256 {e(art["sha256"][:12])}…</p></div>'
            )

    # -- logs
    logs = [s for s in steps if s.get("log")]
    if logs:
        parts.append("<h2>Logs</h2>")
        for step in logs:
            path = bundle / step["log"]
            body = (
                path.read_text(errors="replace")
                if path.is_file()
                else f"({step['log']} is missing from this bundle)"
            )
            code = step.get("exit_code")
            label = f"{step.get('id')} · {step.get('title')}"
            if code is not None:
                label += f" (exit {code})"
            parts.append(
                f"<details><summary>{e(label)}</summary>"
                f'<pre>{e(_clip(body))}</pre></details>'
            )

    # -- provenance
    if arts:
        parts.append("<h2>Provenance</h2><table><tr><th>Artifact</th><th>Size</th>"
                     "<th>sha256</th></tr>")
        for art in arts:
            parts.append(
                f'<tr><td class="mono">{e(art["path"])}</td>'
                f'<td>{e(_size(art.get("bytes")))}</td>'
                f'<td class="mono">{e(art["sha256"][:16])}…</td></tr>'
            )
        parts.append("</table>")

    if ci.get("url"):
        parts.append(
            f'<p class="note">CI run: <a href="{e(str(ci["url"]))}">{e(str(ci["url"]))}</a></p>'
        )

    # -- redactions
    redactions = manifest.get("redactions") or []
    if redactions:
        parts.append("<h2>Redaction report</h2><div class=\"card\">")
        for r in redactions:
            if isinstance(r, dict):
                parts.append(
                    f'<p class="note">{e(str(r.get("path", "?")))}: '
                    f'{e(str(r.get("count", "?")))} × {e(str(r.get("pattern", "?")))}</p>'
                )
            else:
                parts.append(f'<p class="note">{e(str(r))}</p>')
        parts.append("</div>")

    parts.append(
        '<p class="footer">Regenerate with '
        f'<code>python -m openharness run harness_evidence --action=render '
        f'--bundle={e(str(bundle))}</code> · verify with <code>--action=verify</code>'
        " · this page is generated, never edited by hand.</p>"
    )
    parts.append("</main></body></html>")
    return "\n".join(parts) + "\n"


def _rel_src(art: dict) -> str:
    return art["path"]


def _src(art: dict, bundle: Path, inline: bool) -> str:
    if not inline:
        return art["path"]
    path = bundle / art["path"]
    if not path.is_file():
        return art["path"]
    if path.stat().st_size > INLINE_BUDGET:
        return art["path"]
    mime = art.get("mime") or "application/octet-stream"
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{data}"


def _duration(ms: Any) -> str:
    if not isinstance(ms, (int, float)):
        return ""
    if ms < 1000:
        return f"{int(ms)}ms"
    return f"{ms / 1000:.1f}s"


def _size(n: Any) -> str:
    if not isinstance(n, int):
        return "?"
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.1f} kB"
    return f"{n / (1024 * 1024):.1f} MB"


def _clip(text: str, limit: int = 20000) -> str:
    return text if len(text) <= limit else text[:limit] + "\n… (truncated)"


