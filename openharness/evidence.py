def _as_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, bytes):
        return value.decode("utf-8", "replace")
    return str(value)


def _parse_ts(value: Any) -> datetime | None:
    if not isinstance(value, str) or not value.strip():
        return None
    try:
        parsed = datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def _next_step_id(manifest: dict) -> str:
    numbers = [
        int(match.group(1))
        for step in manifest.get("steps", [])
        if (match := re.fullmatch(r"s(\d+)", str(step.get("id", ""))))
    ]
    return f"s{max(numbers, default=0) + 1}"


def _mime_for(path: Path) -> str:
    """Sniff known magic bytes first; fall back to the filename suffix."""
    try:
        head = path.read_bytes()[:16]
    except OSError:
        head = b""
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "image/webp"
    if head.startswith(b"\x1aE\xdf\xa3"):
        return "video/webm"
    if len(head) >= 12 and head[4:8] == b"ftyp":
        return "video/mp4"
    if head.startswith(b"%PDF"):
        return "application/pdf"
    if head.startswith(b"PK\x03\x04"):
        return "application/zip"
    guessed, _ = mimetypes.guess_type(path.name)
    return guessed or "application/octet-stream"


def _role_for(mime: str, path: Path) -> str:
    """Infer a role from MIME and suffix; an explicit `role` always wins."""
    if mime.startswith("image/"):
        return "screenshot"
    if mime.startswith("video/"):
        return "video"
    if path.suffix.lower() == ".har":
        return "har"
    if path.suffix.lower() in (".zip", ".trace") or mime == "application/json":
        return "trace"
    return "attachment"


def _copy_into_raw(bundle: Path, step_id: str, src: Path) -> str:
    """Copy an artifact under `raw/<step>/`, or reuse a path already there."""
    try:
        rel = src.relative_to(bundle)
        if rel.parts and rel.parts[0] == "raw":
            return rel.as_posix()
    except ValueError:
        pass
    target_dir = bundle / "raw" / step_id
    target_dir.mkdir(parents=True, exist_ok=True)
    target = target_dir / src.name
    stem, suffix = target.stem, target.suffix
    n = 2
    while target.exists():
        target = target_dir / f"{stem}-{n}{suffix}"
        n += 1
    shutil.copy2(src, target)
    return target.relative_to(bundle).as_posix()


def record_step(
    bundle: Path | str,
    *,
    title: str = "",
    cmd: str,
    cwd: str = ".",
    timeout: int = 0,
    expected_failure: bool = False,
    step_id: str = "",
    note: str = "",
) -> dict[str, Any]:
    """Run a command and record its real exit code, duration and log.

    The command is run with a shell so ordinary pipelines work. Its output and
    the command line are redacted before they are hashed, so a token printed by
    the command does not become evidence that `verify` has to reject.
    """
    bundle = Path(bundle)
    manifest = load(bundle)
    if not cmd.strip():
        raise EvidenceError("cmd is required")
    if timeout < 0:
        raise EvidenceError("timeout must be zero (no limit) or positive")
    sid = (step_id or _next_step_id(manifest)).strip()
    if not sid:
        raise EvidenceError("step id must not be empty")
    if any(s.get("id") == sid for s in manifest["steps"]):
        raise EvidenceError(f"step {sid!r} already exists")

    repo = _guess_repo(bundle) or Path.cwd()
    workdir = Path(cwd).expanduser()
    if not workdir.is_absolute():
        workdir = repo / workdir
    workdir = workdir.resolve()
    if not workdir.is_dir():
        raise EvidenceError(f"cwd is not a directory: {workdir}")
    try:
        cwd_rel = workdir.relative_to(repo).as_posix()
    except ValueError:
        cwd_rel = str(workdir)

    safe_title, title_redactions = redact_value(title)
    safe_cmd, cmd_redactions = redact_value(cmd)
    safe_note, note_redactions = redact_value(note)

    started = datetime.now(timezone.utc)
    t0 = time.monotonic()
    timed_out = False
    try:
        run = sp.run(
            cmd,
            shell=True,
            cwd=str(workdir),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout or None,
        )
        code = run.returncode
        stdout, stderr = run.stdout, run.stderr
    except sp.TimeoutExpired as ex:
        timed_out = True
        code = 124
        stdout = _as_text(ex.stdout)
        stderr = _as_text(ex.stderr) + f"\n[timed out after {timeout}s]"
    duration_ms = int((time.monotonic() - t0) * 1000)

    log_rel = f"logs/{sid}.log"
    log_path = bundle / log_rel
    log_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text(
        f"$ {safe_cmd}\n"
        f"cwd: {cwd_rel}\n"
        f"started: {started.strftime('%Y-%m-%dT%H:%M:%SZ')}\n"
        f"--- stdout ---\n{stdout}"
        + ("" if stdout.endswith("\n") else "\n")
        + f"--- stderr ---\n{stderr}"
        + ("" if stderr.endswith("\n") else "\n")
        + f"--- exit {code} in {duration_ms}ms ---\n"
    )
    redactions = redact_text(log_path, log_rel)

    step: dict[str, Any] = {
        "id": sid,
        "title": safe_title.strip() or safe_cmd.strip(),
        "kind": "command",
        "status": "pass" if code == 0 else "fail",
        "started_at": started.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "duration_ms": duration_ms,
        "cmd": safe_cmd,
        "cwd": cwd_rel,
        "exit_code": code,
        "log": log_rel,
        "artifacts": [],
    }
    if safe_note.strip():
        step["note"] = safe_note.strip()
    if expected_failure:
        step["expected_failure"] = True
    if timed_out:
        step["note"] = (
            (step.get("note", "") + "; ") if step.get("note") else ""
        ) + f"timed out after {timeout}s"

    manifest["steps"].append(step)
    for entry in title_redactions:
        manifest["redactions"].append({**entry, "path": f"steps[{sid}].title"})
    for entry in cmd_redactions:
        manifest["redactions"].append({**entry, "path": f"steps[{sid}].cmd"})
    for entry in note_redactions:
        manifest["redactions"].append({**entry, "path": f"steps[{sid}].note"})
    manifest["redactions"].extend(redactions)
    _write_manifest(bundle, manifest)
    return step


def record_attach(
    bundle: Path | str,
    file: Path | str,
    *,
    step_id: str = "",
    caption: str = "",
    role: str = "",
    allow_old: bool = False,
    by: str = "",
    snippet: str = "",
) -> dict[str, Any]:
    """Attach an existing file to a step, copying it under `raw/<step>/`.

    A file older than the step's start is refused unless `allow_old` is set:
    an old screenshot must not be passed off as this run. When the bundle has
    no steps yet, a `manual` step is created and dated from the artifact, which
    is how a human-owned gate records a walkthrough.
    """
    bundle = Path(bundle)
    manifest = load(bundle)
    src = Path(file).expanduser()
    if not src.is_absolute():
        src = Path.cwd() / src
    src = src.resolve()
    if not src.is_file():
        raise EvidenceError(f"file does not exist: {src}")

    safe_caption, caption_redactions = redact_value(caption)
    safe_snippet, snippet_redactions = redact_value(snippet)

    steps = manifest["steps"]
    step: dict[str, Any] | None = None
    if step_id:
        step = next((s for s in steps if s.get("id") == step_id), None)
        if step is None:
            raise EvidenceError(f"unknown step {step_id!r}; run --action=step first")
    elif steps:
        step = steps[-1]
    else:
        mtime = datetime.fromtimestamp(src.stat().st_mtime, timezone.utc)
        step = {
            "id": _next_step_id(manifest),
            "title": safe_caption.strip() or src.name,
            "kind": "manual",
            "status": "manual",
            "started_at": mtime.strftime("%Y-%m-%dT%H:%M:%SZ"),
            "artifacts": [],
        }
        if by.strip():
            step["captured_by"] = by.strip()
        steps.append(step)

    sid = step["id"]
    started = _parse_ts(step.get("started_at"))
    mtime = datetime.fromtimestamp(src.stat().st_mtime, timezone.utc)
    if started and mtime < started - timedelta(seconds=5) and not allow_old:
        raise EvidenceError(
            f"{src} is older than step {sid} "
            f"({mtime.isoformat()} < {started.isoformat()}); "
            "capture it during the step or pass --allow-old"
        )

    rel = _copy_into_raw(bundle, sid, src)
    path = bundle / rel
    mime = _mime_for(path)
    redactions = redact_text(path, rel) if _is_text(path, mime) else []
    art: dict[str, Any] = {
        "path": rel,
        "mime": mime,
        "sha256": sha256(path),
        "bytes": path.stat().st_size,
        "role": role.strip() or _role_for(mime, path),
    }
    if safe_caption.strip():
        art["caption"] = safe_caption.strip()
    if safe_snippet.strip():
        art["snippet"] = safe_snippet.strip()
    if by.strip():
        art["captured_by"] = by.strip()
    step.setdefault("artifacts", []).append(art)
    art_ref = f"steps[{sid}].artifacts[{len(step['artifacts']) - 1}].caption"
    for entry in caption_redactions:
        manifest["redactions"].append({**entry, "path": art_ref})
    snippet_ref = art_ref[:-len(".caption")] + ".snippet" if art_ref.endswith(".caption") else art_ref
    for entry in snippet_redactions:
        manifest["redactions"].append({**entry, "path": snippet_ref})
    manifest["redactions"].extend(redactions)
    _write_manifest(bundle, manifest)
    return art


def verify(
    bundle: Path | str,
    repo: Path | str | None = None,
    head: str | None = None,
) -> Report:
    """Check a bundle against its manifest, the files on disk, and git.

    `repo` defaults to the bundle's repository root when it can be found, else
    the current directory. `head` overrides the commit the manifest is compared
    against (defaults to `git rev-parse HEAD`).
    """
    bundle = Path(bundle)
    report = Report(bundle=bundle)
    if not bundle.is_dir():
        report.findings.append(Finding("error", "missing-bundle", f"{bundle} is not a directory"))
        return report
    try:
        manifest = load(bundle)
    except EvidenceError as ex:
        report.findings.append(Finding("error", "invalid-manifest", str(ex)))
        return report

    repo_path = Path(repo) if repo is not None else _guess_repo(bundle)

    # -- a scratch bundle must stay untracked; a tracked-root bundle is meant
    #    to be committed, so git tracking it is expected, not an error.
    tracked = _tracked_files(repo_path, bundle) if repo_path else []
    in_tracked_root = repo_path is not None and _in_tracked_root(repo_path, bundle)
    head_now = _git_head(repo_path) if repo_path else None
    if tracked and not in_tracked_root:
        report.findings.append(
            Finding(
                "error",
                "tracked-bundle",
                "bundle is tracked by git but lives outside "
                f"{TRACKED_ROOT}/ (scratch evidence must stay local): "
                + ", ".join(tracked[:3])
                + (" …" if len(tracked) > 3 else ""),
            )
        )
    elif repo_path is None or head_now is None:
        report.findings.append(
            Finding("warning", "no-git", "no git repository found; cannot confirm the bundle's tracking state")
        )
    if in_tracked_root and not tracked and head_now:
        report.findings.append(
            Finding(
                "warning",
                "untracked-bundle",
                f"bundle lives under {TRACKED_ROOT}/ but git is not tracking it yet "
                "— `git add` it to publish the evidence",
            )
        )

    # -- commit binding
    recorded = (manifest.get("repo") or {}).get("head") or ""
    expected = head or (_git_head(repo_path) if repo_path else None)
    if not recorded:
        report.findings.append(Finding("error", "no-commit", "manifest.repo.head is empty"))
    elif expected is None:
        report.findings.append(
            Finding("warning", "no-head", "git HEAD unavailable; commit binding not checked")
        )
    elif not _same_commit(recorded, expected):
        report.findings.append(
            Finding(
                "error",
                "commit-mismatch",
                f"manifest claims {recorded} but the checked commit is {expected}",
            )
        )

    # -- verdict vs steps
    a_recorded = manifest["verdict"]
    bad_steps = [
        s for s in manifest["steps"]
        if s.get("status") == "fail" and not s.get("expected_failure")
    ]
    if a_recorded == "pass" and bad_steps:
        names = ", ".join(s.get("id", "?") for s in bad_steps)
        report.findings.append(
            Finding(
                "error",
                "verdict-contradicts-steps",
                f"verdict is pass but steps failed: {names} (mark expected_failure to allow)",
            )
        )
    for step in manifest["steps"]:
        if step.get("kind") != "command":
            continue
        code = step.get("exit_code")
        if step.get("status") == "pass" and code != 0:
            report.findings.append(
                Finding(
                    "error",
                    "exit-code-contradicts-status",
                    f"step {step.get('id')} is pass but exit_code is {code}",
                )
            )
        if step.get("status") == "fail" and code == 0 and not step.get("expected_failure"):
            report.findings.append(
                Finding(
                    "warning",
                    "zero-exit-failure",
                    f"step {step.get('id')} is fail but exit_code is 0",
                )
            )

    # -- logs and artifacts must exist, and match their hashes
    for step in manifest["steps"]:
        log = step.get("log")
        if log:
            path = bundle / log
            if not path.is_file():
                report.findings.append(
                    Finding("error", "missing-log", f"step {step.get('id')}: {log} does not exist")
                )
            else:
                for name, line in _secret_hits(path):
                    report.findings.append(
                        Finding(
                            "error",
                            "secret-in-log",
                            f"{log}:{line} looks like a {name} (redact it before rendering)",
                        )
                    )
    for step, art in iter_artifacts(manifest):
        rel = art["path"]
        path = bundle / rel
        if not path.is_file():
            report.findings.append(
                Finding("error", "missing-artifact", f"step {step.get('id')}: {rel} does not exist")
            )
            continue
        size = path.stat().st_size
        if art.get("bytes") != size:
            report.findings.append(
                Finding(
                    "error",
                    "size-mismatch",
                    f"{rel} is {size} bytes, manifest says {art.get('bytes')}",
                )
            )
        digest = sha256(path)
        if digest != art.get("sha256"):
            report.findings.append(
                Finding(
                    "error",
                    "hash-mismatch",
                    f"{rel} hashes to {digest[:12]}…, manifest says {art['sha256'][:12]}…",
                )
            )
        if _is_text(path, art.get("mime", "")):
            for name, line in _secret_hits(path):
                report.findings.append(
                    Finding(
                        "error",
                        "secret-in-artifact",
                        f"{rel}:{line} looks like a {name} (redact it before rendering)",
                    )
                )

    # -- an empty bundle is structurally fine and evidentially worthless
    if not manifest["steps"]:
        report.findings.append(
            Finding(
                "warning",
                "empty-bundle",
                "no steps were recorded — this bundle proves nothing yet",
            )
        )

    # -- the page must not advertise a CI run it cannot name
    ci = manifest.get("ci") or {}
    if ci.get("conclusion") == "success" and not ci.get("sha"):
        report.findings.append(
            Finding("error", "ci-without-sha", "ci.conclusion is success but ci.sha is missing")
        )
    if ci.get("sha") and ci.get("sha") != recorded:
        report.findings.append(
            Finding(
                "warning",
                "ci-sha-differs",
                f"ci.sha {ci['sha']} differs from repo.head {recorded}",
            )
        )

    return report


def _same_commit(a: str, b: str) -> bool:
    a, b = (a or "").strip(), (b or "").strip()
    if not a or not b:
        return False
    if a == b:
        return True
    short, full = (a, b) if len(a) <= len(b) else (b, a)
    return len(short) >= 7 and full.startswith(short)


def _guess_repo(bundle: Path) -> Path | None:
    """Walk up looking for a repo containing `.openharness/` or `.git`."""
    for parent in [bundle, *bundle.parents]:
        if (parent / ".git").exists() or (parent / ".openharness").is_dir():
            return parent
    return None


# -------------------------------------------------------------------- render

def render(bundle: Path | str, inline: bool = False) -> dict[str, Path]:
    """Write `index.html` and `SUMMARY.md` from the manifest; returns their paths."""
    bundle = Path(bundle)
    manifest = load(bundle)
    html_path = bundle / "index.html"
    md_path = bundle / "SUMMARY.md"
    html_path.write_text(_page(manifest, bundle, inline=inline))
    md_path.write_text(summary_markdown(manifest))
    return {"html": html_path, "summary": md_path}


def summary_markdown(manifest: dict) -> str:
    repo = manifest.get("repo") or {}
    ci = manifest.get("ci") or {}
    steps = manifest.get("steps") or []
    arts = [a for _, a in iter_artifacts(manifest)]
    images = [a for a in arts if a.get("mime", "").startswith("image/")]
    videos = [a for a in arts if a.get("mime", "").startswith("video/")]
    lines = [
        f"## Evidence — {manifest['feature']}"
        + (f" · wave {manifest['wave']}" if manifest.get("wave") else ""),
        "",
        f"- verdict: **{manifest['verdict']}**",
        f"- run: `{manifest['run_id']}`",
        f"- head: `{repo.get('head') or 'unknown'}`"
        + (f" on `{repo['branch']}`" if repo.get("branch") else ""),
    ]
    if ci.get("pr"):
        lines.append(f"- CI: PR #{ci['pr']} — {ci.get('conclusion') or 'unknown'} @ `{ci.get('sha') or '?'}`")
    if manifest.get("summary"):
        lines += ["", manifest["summary"]]
    lines += [
        "",
        f"- steps: {len(steps)} · artifacts: {len(arts)}"
        f" · screenshots: {len(images)} · recordings: {len(videos)}",
    ]
    not_verified = manifest.get("not_verified") or []
    if not_verified:
        lines += ["", "**Not verified:** " + "; ".join(not_verified)]
    if not steps and not arts:
        lines += ["", "_Nothing was captured in this run — this bundle proves nothing yet._"]
    return "\n".join(lines) + "\n"


def _page(manifest: dict, bundle: Path, inline: bool) -> str:
    repo = manifest.get("repo") or {}
    ci = manifest.get("ci") or {}
    steps = manifest.get("steps") or []
    arts = [a for _, a in iter_artifacts(manifest)]
    images = [a for a in arts if a.get("mime", "").startswith("image/")]
    videos = [a for a in arts if a.get("mime", "").startswith("video/")]
    verdict = manifest["verdict"]
    e = html.escape
    empty = not steps and not arts

    chips = [
        f'<span class="chip verdict v-{e(verdict)}"><b>{e(verdict.upper())}</b></span>',
        f'<span class="chip">run <b>{e(manifest["run_id"])}</b></span>',
    ]
    if repo.get("head"):
        chips.append(f'<span class="chip">head <b>{e(repo["head"])}</b></span>')
    if repo.get("branch"):
        chips.append(f'<span class="chip">branch <b>{e(repo["branch"])}</b></span>')
    if ci.get("pr"):
        chips.append(f'<span class="chip">PR <b>#{e(str(ci["pr"]))}</b></span>')
    if ci.get("conclusion"):
        chips.append(
            f'<span class="chip">CI <b>{e(str(ci["conclusion"]))}</b>'
            + (f' @ {e(str(ci.get("sha")))}' if ci.get("sha") else "")
            + "</span>"
        )

    parts = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        f"<title>Evidence — {e(manifest['feature'])} · {e(manifest['run_id'])}</title>",
        f"<style>{_CSS}</style></head><body><main>",
        f'<p class="sub">Evidence bundle · generated from evidence.json · {e(SCHEMA)}</p>',
        f"<h1>{e(manifest['feature'])}"
        + (f" — wave {e(str(manifest['wave']))}" if manifest.get("wave") else "")
        + "</h1>",
        '<div class="chips">' + "".join(chips) + "</div>",
        "<h2>What this proves</h2>",
    ]
    if manifest.get("summary"):
        parts.append(f'<div class="card">{e(manifest["summary"])}</div>')
    else:
        parts.append('<div class="card"><em>No summary was recorded for this run.</em></div>')

    counts = (
        f"steps {len(steps)} · artifacts {len(arts)} · screenshots {len(images)}"
        f" · recordings {len(videos)}"
    )
    parts.append(f'<p class="sub">{e(counts)}</p>')

    not_verified = manifest.get("not_verified") or []
    if not_verified:
        items = "".join(f"<li>{e(str(x))}</li>" for x in not_verified)
        parts.append(
            '<div class="card notverified"><strong>What was not verified</strong>'
            f"<ul>{items}</ul></div>"
        )

    if empty:
        parts.append(
            '<div class="card empty"><strong>Nothing was captured in this run.</strong>'
            "<p>No steps, screenshots, recordings or logs are attached to this bundle, "
            "so it proves nothing yet. Record at least one step before using it as "
            "evidence for a wave.</p></div>"
        )

    # -- walkthrough
    if steps:
        parts.append("<h2>Walkthrough</h2>")
        for step in steps:
            status = step.get("status", "manual")
            dur = step.get("duration_ms")
            note = step.get("note")
            expected = step.get("expected_failure")
            details = [
                f'<div class="step {e(status)}">',
                f'<span class="dot"></span><div>',
                f'<div><b>{e(step.get("title") or step.get("id") or "")}</b> '
                f'<span class="pill">{e(status)}</span>'
                + (' <span class="note">(expected failure)</span>' if expected else "")
                + "</div>",
            ]
            if step.get("cmd"):
                details.append(f'<div class="cmd">{e(step["cmd"])}</div>')
            if note:
                details.append(f'<div class="note">{e(str(note))}</div>')
            details.append("</div>")
            details.append(f'<span class="note">{e(_duration(dur))}</span></div>')
            parts.append("".join(details))

    # -- screenshots
    if images:
        parts.append("<h2>Screenshots</h2><div class=\"gallery\">")
        for art in images:
            src = _src(art, bundle, inline)
            caption = art.get("caption") or art["path"]
            snippet_html = ""
            if art.get("snippet"):
                snippet_html = (
                    f'<pre class="snippet"><code>{e(str(art["snippet"]))}</code></pre>'
                )
            parts.append(
                "<figure>"
                f'<a href="{e(_rel_src(art))}"><img src="{e(src)}" alt="{e(str(caption))}" loading="lazy"></a>'
                + snippet_html +
                f"<figcaption><b>{e(str(caption))}</b><br>"
                f'<span class="mono">sha256 {e(art["sha256"][:12])}…</span></figcaption>'
                "</figure>"
            )
        parts.append("</div>")

    # -- recording
    if videos:
        parts.append("<h2>Recording</h2>")
        for art in videos:
            src = _rel_src(art)
            parts.append(
                '<div class="card">'
                f'<video controls preload="metadata" src="{e(src)}"></video>'
                f'<p class="note">{e(art.get("caption") or art["path"])} · '
                f'{e(_size(art.get("bytes")))} · sha256 {e(art["sha256"][:12])}…</p></div>'
            )

    # -- documents (self-contained HTML artifacts render inline)
    docs = [a for a in arts if a.get("mime") == "text/html"]
    if docs:
        parts.append("<h2>Documents</h2>")
        for art in docs:
            caption = art.get("caption") or art["path"]
            parts.append(
                '<div class="card">'
                f'<p class="note"><b>{e(str(caption))}</b> · '
                f'{e(_size(art.get("bytes")))} · sha256 {e(art["sha256"][:12])}… · '
                f'<a href="{e(_rel_src(art))}">open file</a></p>'
                f'<iframe src="{e(_rel_src(art))}" style="width:100%;height:720px;'
                'border:1px solid var(--line);border-radius:8px;background:#fff"></iframe>'
                "</div>"
            )

    # -- logs
    logs = [s for s in steps if s.get("log")]
    if logs:
        parts.append("<h2>Logs</h2>")
        for step in logs:
            path = bundle / step["log"]
            body = (
                path.read_text(errors="replace")
                if path.is_file()
                else f"({step['log']} is missing from this bundle)"
            )
            code = step.get("exit_code")
            label = f"{step.get('id')} · {step.get('title')}"
            if code is not None:
                label += f" (exit {code})"
            parts.append(
                f"<details><summary>{e(label)}</summary>"
                f'<pre>{e(_clip(body))}</pre></details>'
            )

    # -- provenance
    if arts:
        parts.append("<h2>Provenance</h2><table><tr><th>Artifact</th><th>Size</th>"
                     "<th>sha256</th></tr>")
        for art in arts:
            parts.append(
                f'<tr><td class="mono">{e(art["path"])}</td>'
                f'<td>{e(_size(art.get("bytes")))}</td>'
                f'<td class="mono">{e(art["sha256"][:16])}…</td></tr>'
            )
        parts.append("</table>")

    if ci.get("url"):
        parts.append(
            f'<p class="note">CI run: <a href="{e(str(ci["url"]))}">{e(str(ci["url"]))}</a></p>'
        )

    # -- redactions
    redactions = manifest.get("redactions") or []
    if redactions:
        parts.append("<h2>Redaction report</h2><div class=\"card\">")
        for r in redactions:
            if isinstance(r, dict):
                parts.append(
                    f'<p class="note">{e(str(r.get("path", "?")))}: '
                    f'{e(str(r.get("count", "?")))} × {e(str(r.get("pattern", "?")))}</p>'
                )
            else:
                parts.append(f'<p class="note">{e(str(r))}</p>')
        parts.append("</div>")

    parts.append(
        '<p class="footer">Regenerate with '
        f'<code>python -m openharness run harness_evidence --action=render '
        f'--bundle={e(str(bundle))}</code> · verify with <code>--action=verify</code>'
        " · this page is generated, never edited by hand.</p>"
    )
    parts.append("</main></body></html>")
    return "\n".join(parts) + "\n"


def _rel_src(art: dict) -> str:
    return art["path"]


def _src(art: dict, bundle: Path, inline: bool) -> str:
    if not inline:
        return art["path"]
    path = bundle / art["path"]
    if not path.is_file():
        return art["path"]
    if path.stat().st_size > INLINE_BUDGET:
        return art["path"]
    mime = art.get("mime") or "application/octet-stream"
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{data}"


def _duration(ms: Any) -> str:
    if not isinstance(ms, (int, float)):
        return ""
    if ms < 1000:
        return f"{int(ms)}ms"
    return f"{ms / 1000:.1f}s"


def _size(n: Any) -> str:
    if not isinstance(n, int):
        return "?"
    if n < 1024:
        return f"{n} B"
    if n < 1024 * 1024:
        return f"{n / 1024:.1f} kB"
    return f"{n / (1024 * 1024):.1f} MB"


def _clip(text: str, limit: int = 20000) -> str:
    return text if len(text) <= limit else text[:limit] + "\n… (truncated)"


