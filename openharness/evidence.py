def list_bundles(
    repo: Path | str,
    feature: str | None = None,
    tracked: bool | None = None,
) -> list[dict[str, Any]]:
    """Every bundle under both roots, newest first, with its headline facts.

    `tracked` filters to one root: `True` for `evidence/`, `False` for the
    scratch `.openharness/evidence/`; `None` (default) lists both.
    """
    roots = [
        bundle_root(repo, tracked=flag)
        for flag in ((False, True) if tracked is None else (tracked,))
    ]
    pattern = f"{feature}/*/evidence.json" if feature else "*/*/evidence.json"
    out: list[dict[str, Any]] = []
    for root in roots:
        if not root.is_dir():
            continue
        for manifest_path in sorted(root.glob(pattern), reverse=True):
            bundle = manifest_path.parent
            try:
                m = load(bundle)
            except EvidenceError as ex:
                out.append(
                    {
                        "bundle": bundle,
                        "feature": bundle.parent.name,
                        "run_id": bundle.name,
                        "invalid": str(ex),
                    }
                )
                continue
            out.append(
                {
                    "bundle": bundle,
                    "feature": m["feature"],
                    "wave": m.get("wave"),
                    "run_id": m["run_id"],
                    "verdict": m["verdict"],
                    "head": (m.get("repo") or {}).get("head") or "",
                    "steps": len(m.get("steps") or []),
                    "artifacts": sum(len(s.get("artifacts") or []) for s in m.get("steps") or []),
                    "summary": m.get("summary") or "",
                    "tracked": _in_tracked_root(Path(repo), bundle),
                }
            )
    out.sort(key=lambda r: str(r.get("run_id") or ""), reverse=True)
    return out
